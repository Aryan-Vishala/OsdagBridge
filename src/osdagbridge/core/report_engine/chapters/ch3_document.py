from ..document import Chapter, Column, RawLatex, Section, Table
from ..facts import ReportFacts
from ..facts.loads import build_load_facts
from ..layout import LayoutHints


def build_chapter_3(facts: ReportFacts) -> Chapter:
    """Build Chapter 3: Loads and Load Combinations.

    Constructs LoadFacts from raw_input_dict (including IRC6 calculations),
    then builds semantic Table components for each load category.
    """
    load_facts = build_load_facts(facts.raw_input_dict or {})

    return Chapter(
        number=3,
        title="Loads and Load Combinations",
        sections=[
            Section(
                title="",
                level=2,
                components=[
                    RawLatex(r"\vspace{1em}"),
                    _dead_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _surfacing_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _live_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _wind_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _seismic_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _temperature_load_table(load_facts),
                    RawLatex(r"\vspace{1em}"),
                    _load_combination_table(load_facts),
                    RawLatex(
                        r"\noindent\textit{Note: All IRC 6 load combinations "
                        r"are auto-generated by OsdagBridge. User-defined custom "
                        r"combinations, if any, are appended.}"
                    ),
                ],
            ),
        ],
    )


