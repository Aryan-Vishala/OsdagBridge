# ---------------------------------------------------------------------------
# Table 3.3 — Live Loads (LL)
# ---------------------------------------------------------------------------

def _live_load_table(lf) -> Table:
    ll = lf.live_load

    vehicles_str = ", ".join(v.vehicle_class for v in ll.vehicles) if ll.vehicles else "None"

    # Impact factors — one entry per vehicle group
    im_parts = []
    seen_im = set()
    for v in ll.vehicles:
        if v.impact_factor and v.impact_factor.value is not None:
            key = v.impact_factor.value
            if key not in seen_im:
                seen_im.add(key)
                im_parts.append(f"{v.vehicle_class}: {v.impact_factor.value:.3f}")
    im_str = ", ".join(im_parts) if im_parts else "N/A"

    braking_str = _fmt(ll.braking_force) if ll.braking_force else "N/A"

    fp_str = "N/A"
    if ll.footway_load:
        fp_str = f"{_fmt(ll.footway_load.intensity)} ({ll.footway_load.load_type})"

    return Table(
        caption="Live Loads (LL)",
        label="",
        columns=[
            Column("Parameter", width="5.5cm"),
            Column("Value", width="10.0cm"),
        ],
        rows=[
            ["Vehicles Considered", vehicles_str],
            ["Impact Factor (IRC 6)", im_str],
            ["Braking Load (IRC 6)", braking_str],
            ["Footpath Live Load (if applicable)", fp_str],
        ],
        layout=LayoutHints(space_after_mm=4),
    )


